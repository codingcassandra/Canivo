// Zone returns the dog's safe zone, or nil if none is set.
func (s *Store) Zone(ctx context.Context, dogID int64) (*geo.Zone, error) {
	var z geo.Zone
	err := s.db.QueryRowContext(ctx, `SELECT lat, lon, radius_m FROM zones WHERE dog_id = $1`, dogID).
		Scan(&z.Lat, &z.Lon, &z.RadiusM)
	if errors.Is(err, sql.ErrNoRows) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	return &z, nil
}

// SetZone sets or, with nil, removes the dog's safe zone.
func (s *Store) SetZone(ctx context.Context, dogID int64, z *geo.Zone) error {
	if z == nil {
		_, err := s.db.ExecContext(ctx, `DELETE FROM zones WHERE dog_id = $1`, dogID)
		return err
	}
	_, err := s.db.ExecContext(ctx,
		`INSERT INTO zones(dog_id, lat, lon, radius_m) VALUES ($1, $2, $3, $4)
		 ON CONFLICT (dog_id) DO UPDATE SET lat = excluded.lat, lon = excluded.lon, radius_m = excluded.radius_m`,
		dogID, z.Lat, z.Lon, z.RadiusM)
	return err
}

// keepFixes is how long GPS history is kept.
const keepFixes = 24 * time.Hour

// AddFixes saves GPS fixes and drops the dog's fixes older than a day.
func (s *Store) AddFixes(ctx context.Context, dogID int64, fixes []geo.Fix) error {
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	for _, f := range fixes {
		if _, err := tx.ExecContext(ctx,
			`INSERT INTO locations(dog_id, at_ms, lat, lon, accuracy_m) VALUES ($1, $2, $3, $4, $5)`,
			dogID, f.At.UnixMilli(), f.Lat, f.Lon, f.AccuracyM); err != nil {
			return err
		}
	}
	if _, err := tx.ExecContext(ctx, `DELETE FROM locations WHERE dog_id = $1 AND at_ms < $2`,
		dogID, time.Now().Add(-keepFixes).UnixMilli()); err != nil {
		return err
	}
	return tx.Commit()
}

// Fixes returns the dog's fixes since a time, oldest first, at most limit
// (the most recent ones).
func (s *Store) Fixes(ctx context.Context, dogID int64, since time.Time, limit int) ([]geo.Fix, error) {
	rows, err := s.db.QueryContext(ctx,
		`SELECT at_ms, lat, lon, accuracy_m FROM locations
		 WHERE dog_id = $1 AND at_ms >= $2 ORDER BY at_ms DESC, id DESC LIMIT $3`,
		dogID, since.UnixMilli(), limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	fixes := []geo.Fix{}
	for rows.Next() {
		var f geo.Fix
		var ms int64
		if err := rows.Scan(&ms, &f.Lat, &f.Lon, &f.AccuracyM); err != nil {
			return nil, err
		}
		f.At = time.UnixMilli(ms).UTC()
		fixes = append(fixes, f)
	}
	for i, j := 0, len(fixes)-1; i < j; i, j = i+1, j-1 {
		fixes[i], fixes[j] = fixes[j], fixes[i]
	}
	return fixes, rows.Err()
}

// CreateUser adds an account. email must already be normalized.
func (s *Store) CreateUser(ctx context.Context, email, passwordHash string) (User, error) {
	u := User{Email: email, CreatedAt: time.Now().UTC()}
	if _, _, err := s.UserByEmail(ctx, email); err == nil {
		return User{}, ErrExists
	}
	err := s.db.QueryRowContext(ctx,
		`INSERT INTO users(email, password_hash, created_at) VALUES ($1, $2, $3) RETURNING id`,
		email, passwordHash, fmtTime(u.CreatedAt)).Scan(&u.ID)
	if err != nil && isUniqueViolation(err) { // lost a race with the same email
		return User{}, ErrExists
	}
	return u, err
}

// UserByEmail returns the account and its password hash.
func (s *Store) UserByEmail(ctx context.Context, email string) (User, string, error) {
	var u User
	var hash, created string
	err := s.db.QueryRowContext(ctx, `SELECT id, email, password_hash, created_at FROM users WHERE email = $1`, email).
		Scan(&u.ID, &u.Email, &hash, &created)
	if errors.Is(err, sql.ErrNoRows) {
		return User{}, "", ErrNotFound
	}
	u.CreatedAt = parseTime(created)
	return u, hash, err
}

func (s *Store) User(ctx context.Context, id int64) (User, error) {
	var u User
	var created string
	err := s.db.QueryRowContext(ctx, `SELECT id, email, created_at FROM users WHERE id = $1`, id).
		Scan(&u.ID, &u.Email, &created)
	if errors.Is(err, sql.ErrNoRows) {
		return User{}, ErrNotFound
	}
	u.CreatedAt = parseTime(created)
	return u, err
}

// CountUsers is used to give dogs from before accounts existed to the first account.
func (s *Store) CountUsers(ctx context.Context) (int, error) {
	var n int
	err := s.db.QueryRowContext(ctx, `SELECT COUNT(*) FROM users`).Scan(&n)
	return n, err
}

// ClaimOrphanDogs gives every dog without an owner to the user.
func (s *Store) ClaimOrphanDogs(ctx context.Context, userID int64) (int64, error) {
	res, err := s.db.ExecContext(ctx, `UPDATE dogs SET owner_id = $1 WHERE owner_id IS NULL`, userID)
	if err != nil {
		return 0, err
	}
	return res.RowsAffected()
}

// Session is a signed-in device. Only a hash of its token is stored, so a
// leaked database can't be used to sign in.
type Session struct {
	UserID  int64
	TTL     time.Duration // how long it lasts after each use
	Expires time.Time
}

func (s *Store) CreateSession(ctx context.Context, tokenHash string, userID int64, ttl time.Duration, now time.Time) error {
	_, err := s.db.ExecContext(ctx,
		`INSERT INTO sessions(token_hash, user_id, ttl_ms, expires_ms) VALUES ($1, $2, $3, $4)`,
		tokenHash, userID, ttl.Milliseconds(), now.Add(ttl).UnixMilli())
	return err
}

// Session returns an unexpired session, or ErrNotFound.
func (s *Store) Session(ctx context.Context, tokenHash string, now time.Time) (Session, error) {
	var ss Session
	var ttl, exp int64
	err := s.db.QueryRowContext(ctx,
		`SELECT user_id, ttl_ms, expires_ms FROM sessions WHERE token_hash = $1 AND expires_ms > $2`,
		tokenHash, now.UnixMilli()).Scan(&ss.UserID, &ttl, &exp)
	if errors.Is(err, sql.ErrNoRows) {
		return Session{}, ErrNotFound
	}
	ss.TTL, ss.Expires = time.Duration(ttl)*time.Millisecond, time.UnixMilli(exp)
	return ss, err
}

func (s *Store) ExtendSession(ctx context.Context, tokenHash string, expires time.Time) error {
	_, err := s.db.ExecContext(ctx, `UPDATE sessions SET expires_ms = $1 WHERE token_hash = $2`, expires.UnixMilli(), tokenHash)
	return err
}

func (s *Store) DeleteSession(ctx context.Context, tokenHash string) error {
	_, err := s.db.ExecContext(ctx, `DELETE FROM sessions WHERE token_hash = $1`, tokenHash)
	return err
}

func (s *Store) DeleteExpiredSessions(ctx context.Context, now time.Time) error {
	_, err := s.db.ExecContext(ctx, `DELETE FROM sessions WHERE expires_ms <= $1`, now.UnixMilli())
	return err
}

func isUniqueViolation(err error) bool {
	msg := strings.ToLower(err.Error())
	return strings.Contains(msg, "unique") || strings.Contains(msg, "duplicate key")
}

func nullID(id int64) any {
	if id == 0 {
		return nil
	}
	return id
}

type scanner interface{ Scan(...any) error }

func scanDog(r scanner) (Dog, error) {
	var d Dog
	var created string
	var baseline sql.NullString
	var owner sql.NullInt64
	if err := r.Scan(&d.ID, &d.Name, &created, &baseline, &owner); err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return Dog{}, ErrNotFound
		}
		return Dog{}, err
	}
	d.CreatedAt = parseTime(created)
	d.OwnerID = owner.Int64
	if baseline.Valid {
		d.Baseline = &monitor.Baseline{}
		if err := json.Unmarshal([]byte(baseline.String), d.Baseline); err != nil {
			return Dog{}, err
		}
	}
	return d, nil
}

func fmtTime(t time.Time) string { return t.UTC().Format(time.RFC3339Nano) }

func parseTime(s string) time.Time {
	t, _ := time.Parse(time.RFC3339Nano, s)
	return t
}
