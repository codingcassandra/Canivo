// Package store persists dogs, their baselines, alerts, safe zones, recent
// GPS fixes and owners' push tokens in SQLite (local dev) or Postgres (deployed). Raw sensor samples are
// not stored. Queries use $N placeholders, which both databases accept.
package store

import (
	"context"
	"database/sql"
	"encoding/json"
	"errors"
	"strings"
	"time"

	"github.com/codingcassandra/Canivo/internal/geo"
	"github.com/codingcassandra/Canivo/internal/monitor"
	"github.com/codingcassandra/Canivo/internal/notify"
	_ "github.com/jackc/pgx/v5/stdlib"
	_ "modernc.org/sqlite"
)

var ErrNotFound = errors.New("not found")

type Dog struct {
	ID        int64             `json:"id"`
	Name      string            `json:"name"`
	CreatedAt time.Time         `json:"created_at"`
	Baseline  *monitor.Baseline `json:"baseline,omitempty"`
}

type Alert struct {
	ID        int64      `json:"id"`
	DogID     int64      `json:"dog_id"`
	StartedAt time.Time  `json:"started_at"`
	EndedAt   *time.Time `json:"ended_at,omitempty"`
	Score     float64    `json:"score"`
	RateBPM   float64    `json:"rate_bpm"`
	Tension   float64    `json:"tension"`
}

type Store struct{ db *sql.DB }

// {{ID}} and {{FLOAT}} are filled in per database by Open.
const schema = `
CREATE TABLE IF NOT EXISTS dogs (
	id         {{ID}},
	name       TEXT NOT NULL,
	created_at TEXT NOT NULL,
	baseline   TEXT
);
CREATE TABLE IF NOT EXISTS alerts (
	id         {{ID}},
	dog_id     BIGINT NOT NULL REFERENCES dogs(id) ON DELETE CASCADE,
	started_at TEXT NOT NULL,
	ended_at   TEXT,
	score      {{FLOAT}} NOT NULL,
	rate_bpm   {{FLOAT}} NOT NULL,
	tension    {{FLOAT}} NOT NULL
);
CREATE INDEX IF NOT EXISTS alerts_dog ON alerts(dog_id, started_at);
CREATE TABLE IF NOT EXISTS push_tokens (
	token      TEXT NOT NULL,
	dog_id     BIGINT NOT NULL REFERENCES dogs(id) ON DELETE CASCADE,
	created_at TEXT NOT NULL,
	PRIMARY KEY (token, dog_id)
);
CREATE TABLE IF NOT EXISTS web_push_subs (
	endpoint   TEXT NOT NULL,
	dog_id     BIGINT NOT NULL REFERENCES dogs(id) ON DELETE CASCADE,
	p256dh     TEXT NOT NULL,
	auth       TEXT NOT NULL,
	created_at TEXT NOT NULL,
	PRIMARY KEY (endpoint, dog_id)
);
CREATE TABLE IF NOT EXISTS zones (
	dog_id   BIGINT PRIMARY KEY REFERENCES dogs(id) ON DELETE CASCADE,
	lat      {{FLOAT}} NOT NULL,
	lon      {{FLOAT}} NOT NULL,
	radius_m {{FLOAT}} NOT NULL
);
CREATE TABLE IF NOT EXISTS locations (
	id         {{ID}},
	dog_id     BIGINT NOT NULL REFERENCES dogs(id) ON DELETE CASCADE,
	at_ms      BIGINT NOT NULL,
	lat        {{FLOAT}} NOT NULL,
	lon        {{FLOAT}} NOT NULL,
	accuracy_m {{FLOAT}} NOT NULL
);
CREATE INDEX IF NOT EXISTS locations_dog ON locations(dog_id, at_ms);`

// pgLockdown enables row-level security with no policies. On Supabase this
// stops the auto-generated public REST API (anon key) from reading the
// tables; the server connects as the table owner, so it is unaffected.
const pgLockdown = `
ALTER TABLE dogs ENABLE ROW LEVEL SECURITY;
ALTER TABLE alerts ENABLE ROW LEVEL SECURITY;
ALTER TABLE push_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE web_push_subs ENABLE ROW LEVEL SECURITY;
ALTER TABLE zones ENABLE ROW LEVEL SECURITY;
ALTER TABLE locations ENABLE ROW LEVEL SECURITY;`

// Open opens (and migrates) a database. dsn is either a Postgres URL
// ("postgres://...") or a SQLite file path (":memory:" in tests).
func Open(dsn string) (*Store, error) {
	var db *sql.DB
	var err error
	var ddl string
	if strings.HasPrefix(dsn, "postgres://") || strings.HasPrefix(dsn, "postgresql://") {
		db, err = sql.Open("pgx", dsn)
		ddl = strings.NewReplacer("{{ID}}", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "{{FLOAT}}", "DOUBLE PRECISION").Replace(schema) + pgLockdown
	} else {
		db, err = sql.Open("sqlite", dsn+"?_pragma=foreign_keys(1)&_pragma=busy_timeout(5000)")
		ddl = strings.NewReplacer("{{ID}}", "INTEGER PRIMARY KEY", "{{FLOAT}}", "REAL").Replace(schema)
	}
	if err != nil {
		return nil, err
	}
	if !strings.HasPrefix(dsn, "postgres") {
		db.SetMaxOpenConns(1) // SQLite allows one writer; also keeps :memory: a single DB
	}
	if _, err := db.Exec(ddl); err != nil {
		db.Close()
		return nil, err
	}
	return &Store{db: db}, nil
}

func (s *Store) Close() error { return s.db.Close() }

func (s *Store) CreateDog(ctx context.Context, name string) (Dog, error) {
	d := Dog{Name: name, CreatedAt: time.Now().UTC()}
	err := s.db.QueryRowContext(ctx, `INSERT INTO dogs(name, created_at) VALUES ($1, $2) RETURNING id`,
		name, fmtTime(d.CreatedAt)).Scan(&d.ID)
	return d, err
}

func (s *Store) Dog(ctx context.Context, id int64) (Dog, error) {
	row := s.db.QueryRowContext(ctx, `SELECT id, name, created_at, baseline FROM dogs WHERE id = $1`, id)
	return scanDog(row)
}

func (s *Store) Dogs(ctx context.Context) ([]Dog, error) {
	rows, err := s.db.QueryContext(ctx, `SELECT id, name, created_at, baseline FROM dogs ORDER BY id`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	dogs := []Dog{}
	for rows.Next() {
		d, err := scanDog(rows)
		if err != nil {
			return nil, err
		}
		dogs = append(dogs, d)
	}
	return dogs, rows.Err()
}

func (s *Store) SetBaseline(ctx context.Context, dogID int64, b *monitor.Baseline) error {
	var v any // NULL clears it
	if b != nil {
		j, err := json.Marshal(b)
		if err != nil {
			return err
		}
		v = string(j)
	}
	_, err := s.db.ExecContext(ctx, `UPDATE dogs SET baseline = $1 WHERE id = $2`, v, dogID)
	return err
}

func (s *Store) StartAlert(ctx context.Context, a Alert) (int64, error) {
	var id int64
	err := s.db.QueryRowContext(ctx,
		`INSERT INTO alerts(dog_id, started_at, score, rate_bpm, tension) VALUES ($1, $2, $3, $4, $5) RETURNING id`,
		a.DogID, fmtTime(a.StartedAt), a.Score, a.RateBPM, a.Tension).Scan(&id)
	return id, err
}

func (s *Store) EndAlert(ctx context.Context, id int64, at time.Time) error {
	_, err := s.db.ExecContext(ctx, `UPDATE alerts SET ended_at = $1 WHERE id = $2`, fmtTime(at), id)
	return err
}

// EndOpenAlerts closes alerts left open by a previous run.
func (s *Store) EndOpenAlerts(ctx context.Context, at time.Time) error {
	_, err := s.db.ExecContext(ctx, `UPDATE alerts SET ended_at = $1 WHERE ended_at IS NULL`, fmtTime(at))
	return err
}

func (s *Store) Alerts(ctx context.Context, dogID int64, limit int) ([]Alert, error) {
	rows, err := s.db.QueryContext(ctx,
		`SELECT id, dog_id, started_at, ended_at, score, rate_bpm, tension
		 FROM alerts WHERE dog_id = $1 ORDER BY started_at DESC, id DESC LIMIT $2`, dogID, limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	alerts := []Alert{}
	for rows.Next() {
		var a Alert
		var started string
		var ended sql.NullString
		if err := rows.Scan(&a.ID, &a.DogID, &started, &ended, &a.Score, &a.RateBPM, &a.Tension); err != nil {
			return nil, err
		}
		a.StartedAt = parseTime(started)
		if ended.Valid {
			t := parseTime(ended.String)
			a.EndedAt = &t
		}
		alerts = append(alerts, a)
	}
	return alerts, rows.Err()
}

func (s *Store) AddPushToken(ctx context.Context, dogID int64, token string) error {
	_, err := s.db.ExecContext(ctx,
		`INSERT INTO push_tokens(token, dog_id, created_at) VALUES ($1, $2, $3) ON CONFLICT DO NOTHING`,
		token, dogID, fmtTime(time.Now()))
	return err
}

func (s *Store) PushTokens(ctx context.Context, dogID int64) ([]string, error) {
	rows, err := s.db.QueryContext(ctx, `SELECT token FROM push_tokens WHERE dog_id = $1`, dogID)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var tokens []string
	for rows.Next() {
		var t string
		if err := rows.Scan(&t); err != nil {
			return nil, err
		}
		tokens = append(tokens, t)
	}
	return tokens, rows.Err()
}

// RemovePushToken deletes a token from every dog (e.g. the app was uninstalled).
func (s *Store) RemovePushToken(ctx context.Context, token string) error {
	_, err := s.db.ExecContext(ctx, `DELETE FROM push_tokens WHERE token = $1`, token)
	return err
}

// AddWebPush saves a browser subscription; re-subscribing updates its keys.
func (s *Store) AddWebPush(ctx context.Context, dogID int64, sub notify.WebSubscription) error {
	_, err := s.db.ExecContext(ctx,
		`INSERT INTO web_push_subs(endpoint, dog_id, p256dh, auth, created_at) VALUES ($1, $2, $3, $4, $5)
		 ON CONFLICT (endpoint, dog_id) DO UPDATE SET p256dh = excluded.p256dh, auth = excluded.auth`,
		sub.Endpoint, dogID, sub.Keys.P256dh, sub.Keys.Auth, fmtTime(time.Now()))
	return err
}

func (s *Store) WebPushSubs(ctx context.Context, dogID int64) ([]notify.WebSubscription, error) {
	rows, err := s.db.QueryContext(ctx, `SELECT endpoint, p256dh, auth FROM web_push_subs WHERE dog_id = $1`, dogID)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var subs []notify.WebSubscription
	for rows.Next() {
		var sub notify.WebSubscription
		if err := rows.Scan(&sub.Endpoint, &sub.Keys.P256dh, &sub.Keys.Auth); err != nil {
			return nil, err
		}
		subs = append(subs, sub)
	}
	return subs, rows.Err()
}

// RemoveWebPush deletes a browser subscription from every dog.
func (s *Store) RemoveWebPush(ctx context.Context, endpoint string) error {
	_, err := s.db.ExecContext(ctx, `DELETE FROM web_push_subs WHERE endpoint = $1`, endpoint)
	return err
}

// Zone returns the dog's safe zone, or nil if none is set.
func (s *Store) Zone(ctx context.Context, dogID int64) (*geo.Zone, error) {
	var z geo.Zone
	err := s.db.QueryRowContext(ctx, `SELECT lat, lon, radius_m FROM zones WHERE dog_id = $1`, dogID).
		Scan(&z.Lat, &z.Lon, &z.RadiusM)
	if errors.Is(err, sql.ErrNoRows) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	return &z, nil
}

// SetZone sets or, with nil, removes the dog's safe zone.
func (s *Store) SetZone(ctx context.Context, dogID int64, z *geo.Zone) error {
	if z == nil {
		_, err := s.db.ExecContext(ctx, `DELETE FROM zones WHERE dog_id = $1`, dogID)
		return err
	}
	_, err := s.db.ExecContext(ctx,
		`INSERT INTO zones(dog_id, lat, lon, radius_m) VALUES ($1, $2, $3, $4)
		 ON CONFLICT (dog_id) DO UPDATE SET lat = excluded.lat, lon = excluded.lon, radius_m = excluded.radius_m`,
		dogID, z.Lat, z.Lon, z.RadiusM)
	return err
}

// keepFixes is how long GPS history is kept.
const keepFixes = 24 * time.Hour

// AddFixes saves GPS fixes and drops the dog's fixes older than a day.
func (s *Store) AddFixes(ctx context.Context, dogID int64, fixes []geo.Fix) error {
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	for _, f := range fixes {
		if _, err := tx.ExecContext(ctx,
			`INSERT INTO locations(dog_id, at_ms, lat, lon, accuracy_m) VALUES ($1, $2, $3, $4, $5)`,
			dogID, f.At.UnixMilli(), f.Lat, f.Lon, f.AccuracyM); err != nil {
			return err
		}
	}
	if _, err := tx.ExecContext(ctx, `DELETE FROM locations WHERE dog_id = $1 AND at_ms < $2`,
		dogID, time.Now().Add(-keepFixes).UnixMilli()); err != nil {
		return err
	}
	return tx.Commit()
}

// Fixes returns the dog's fixes since a time, oldest first, at most limit
// (the most recent ones).
func (s *Store) Fixes(ctx context.Context, dogID int64, since time.Time, limit int) ([]geo.Fix, error) {
	rows, err := s.db.QueryContext(ctx,
		`SELECT at_ms, lat, lon, accuracy_m FROM locations
		 WHERE dog_id = $1 AND at_ms >= $2 ORDER BY at_ms DESC, id DESC LIMIT $3`,
		dogID, since.UnixMilli(), limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	fixes := []geo.Fix{}
	for rows.Next() {
		var f geo.Fix
		var ms int64
		if err := rows.Scan(&ms, &f.Lat, &f.Lon, &f.AccuracyM); err != nil {
			return nil, err
		}
		f.At = time.UnixMilli(ms).UTC()
		fixes = append(fixes, f)
	}
	for i, j := 0, len(fixes)-1; i < j; i, j = i+1, j-1 {
		fixes[i], fixes[j] = fixes[j], fixes[i]
	}
	return fixes, rows.Err()
}

type scanner interface{ Scan(...any) error }

func scanDog(r scanner) (Dog, error) {
	var d Dog
	var created string
	var baseline sql.NullString
	if err := r.Scan(&d.ID, &d.Name, &created, &baseline); err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return Dog{}, ErrNotFound
		}
		return Dog{}, err
	}
	d.CreatedAt = parseTime(created)
	if baseline.Valid {
		d.Baseline = &monitor.Baseline{}
		if err := json.Unmarshal([]byte(baseline.String), d.Baseline); err != nil {
			return Dog{}, err
		}
	}
	return d, nil
}

func fmtTime(t time.Time) string { return t.UTC().Format(time.RFC3339Nano) }

func parseTime(s string) time.Time {
	t, _ := time.Parse(time.RFC3339Nano, s)
	return t
}
